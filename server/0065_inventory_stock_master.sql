-- ── the switch (admin) ───────────────────────────────────────────────────────
create or replace function public.set_zoho_stock_master(p_master text)
returns text language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if coalesce((select role from app_user where id = auth.uid()), '') <> 'admin' then
    raise exception 'Only an admin can change who holds the stock.';
  end if;
  if p_master not in ('ctp', 'zoho') then raise exception 'stock master must be ctp or zoho'; end if;
  update zoho_config set stock_master = p_master, updated_at = now(), updated_by = auth.uid() where id = 1;
  insert into zoho_push_log (doc_type, action, ok, message, actor)
  values ('config', 'stock_master', true, 'Stock master: ' || upper(p_master), auth.uid());
  return p_master;
end $$;
revoke all on function public.set_zoho_stock_master(text) from public, anon;
grant execute on function public.set_zoho_stock_master(text) to authenticated;

-- ── the stock cache (server only): Zoho Inventory items list → zoho_item + part ──
-- p_items: [{ item_id, stock_on_hand, available_stock, available_for_sale, actual_available_stock }]
create or replace function public.apply_zoho_stock(p_items jsonb)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare n_item int := 0; n_part int := 0;
begin
  if auth.uid() is not null then
    raise exception 'apply_zoho_stock is called by the server, not from a session.' using errcode = '42501';
  end if;
  with x as (
    select e->>'item_id' as item_id, nullif(e->>'stock_on_hand', '')::numeric as soh,
           nullif(e->>'available_stock', '')::numeric as avail,
           coalesce(nullif(e->>'available_for_sale', '')::numeric, nullif(e->>'available_stock', '')::numeric) as afs,
           nullif(e->>'actual_available_stock', '')::numeric as actual
      from jsonb_array_elements(p_items) e)
  update zoho_item z set stock_on_hand = x.soh, available_stock = x.avail, available_for_sale = x.afs,
         actual_available = x.actual, stock_synced_at = now()
    from x where z.zoho_item_id = x.item_id;
  get diagnostics n_item = row_count;
  -- the part row only when something changed (each change is a sync row on every staff phone)
  update part p set zoho_stock_on_hand = z.stock_on_hand, zoho_available_for_sale = z.available_for_sale,
         zoho_committed = greatest(coalesce(z.stock_on_hand, 0) - coalesce(z.available_for_sale, z.stock_on_hand, 0), 0),
         zoho_stock_at = now(), updated_at = now()
    from zoho_item z
   where z.part_id = p.id and z.status = 'active'
     and (p.zoho_stock_on_hand is distinct from z.stock_on_hand or p.zoho_available_for_sale is distinct from z.available_for_sale);
  get diagnostics n_part = row_count;
  update zoho_config set stock_synced_at = now() where id = 1;
  return jsonb_build_object('items', n_item, 'parts_changed', n_part);
end $$;
revoke all on function public.apply_zoho_stock(jsonb) from public, anon, authenticated;
grant execute on function public.apply_zoho_stock(jsonb) to service_role;

-- ── goods out recorded after Zoho shipped it (server only) ───────────────────
-- Same status change as fulfil_order (so the 0059/0061 fulfil gate trigger still
-- applies), the CTP hold released, but NO CTP sale movement: Zoho's shipment
-- took the stock out.
create or replace function public.record_goods_out(p_order_id bigint, p_actor uuid, p_ship jsonb)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_o record;
begin
  if auth.uid() is not null then
    raise exception 'record_goods_out is called by the server, not from a session.' using errcode = '42501';
  end if;
  select id, number, status, fulfilled_at into v_o from sales_order where id = p_order_id and deleted_at is null for update;
  if v_o.id is null then raise exception 'No such order.' using errcode = '42704'; end if;
  update sales_order set
    zoho_package_id = coalesce(p_ship->>'package_id', zoho_package_id),
    zoho_package_number = coalesce(p_ship->>'package_number', zoho_package_number),
    zoho_shipment_id = coalesce(p_ship->>'shipment_id', zoho_shipment_id),
    zoho_shipment_number = coalesce(p_ship->>'shipment_number', zoho_shipment_number),
    zoho_shipment_status = coalesce(p_ship->>'shipment_status', zoho_shipment_status),
    updated_at = now()
  where id = v_o.id;
  if v_o.status in ('fulfilled', 'invoiced') then
    return jsonb_build_object('order_id', v_o.id, 'number', v_o.number, 'status', v_o.status, 'already', true);
  end if;
  if v_o.status <> 'confirmed' then
    raise exception '% is %, not accepted — only an accepted order can go out.', v_o.number, v_o.status using errcode = '22023';
  end if;
  perform public.release_order(v_o.id, 'shipped in Zoho');
  update sales_order set status = 'fulfilled', fulfilled_at = now(), updated_at = now(),
         notes = concat_ws(E'\n', nullif(notes, ''), format('[%s] Goods out — Zoho package %s, shipment %s%s',
                   to_char(now() at time zone 'Africa/Johannesburg', 'YYYY-MM-DD HH24:MI'),
                   coalesce(p_ship->>'package_number', '?'), coalesce(p_ship->>'shipment_number', '?'),
                   case when p_actor is null then '' else ' (by ' || coalesce((select display_name from app_user where id = p_actor), 'staff') || ')' end))
   where id = v_o.id;
  return jsonb_build_object('order_id', v_o.id, 'number', v_o.number, 'status', 'fulfilled', 'already', false);
end $$;
revoke all on function public.record_goods_out(bigint, uuid, jsonb) from public, anon, authenticated;
grant execute on function public.record_goods_out(bigint, uuid, jsonb) to service_role;

-- ── CTP fulfil refuses while Zoho holds the stock ────────────────────────────
create or replace function public.fulfil_order_zoho_guard()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if new.reason = 'sale' and new.ref_type = 'sales_order'
     and coalesce((select stock_master from zoho_config where id = 1), 'ctp') = 'zoho' then
    raise exception 'Zoho Inventory holds the stock now — use "Ship in Zoho" (package + shipment), not the CTP fulfil.' using errcode = '22023';
  end if;
  if coalesce((select ctp_ledger_frozen from zoho_config where id = 1), false) and coalesce(new.origin, '') <> 'cutover' then
    raise exception 'The CTP stock ledger is frozen (Zoho is the stock master) — book stock in Zoho.' using errcode = '22023';
  end if;
  return new;
end $$;
drop trigger if exists stock_movement_zoho_guard on public.stock_movement;
create trigger stock_movement_zoho_guard before insert on public.stock_movement
  for each row execute function public.fulfil_order_zoho_guard();

commit;
