-- CTP Core 0065 — Phase 3 on Zoho Inventory, behind the rehearsal switch (23 Oct 2026).
--
-- zoho_config.stock_master = 'ctp' (default: today's CTP ledger) | 'zoho' (Inventory leads):
--   * Fulfil      → zoho-push {action:"ship"}: package + shipment from the confirmed SO in
--                   Zoho Inventory, then record_goods_out() — goods-out recorded in CTP, NO
--                   CTP sale movement (Zoho's shipment moves the stock). fulfil_order()
--                   refuses in this mode, so nothing double-counts.
--   * Count       → zoho-push {action:"adjust"}: an Inventory adjustment (counted − Zoho on
--                   hand), logged in zoho_stock_adjustment.
--   * Receiving   → zoho-push {action:"receive"}: an Inventory purchase receive against a
--                   Zoho PO, logged in zoho_purchase_receive.
--   * Stock shown → part.zoho_* columns (the Zoho stock cache, refreshed with the 10-min
--                   read-back and by the zoho-push "hook" webhook). Staff phones receive them
--                   through the existing SELECT * part stream; customers' list is unchanged.
-- ctp_ledger_frozen: set at cut-over (docs/09) — refuses new CTP stock movements except
-- origin 'cutover'. OFF during the rehearsal.
begin;

