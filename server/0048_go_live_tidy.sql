-- ── schema ──────────────────────────────────────────────────────────────────
alter table public.sales_order   add column if not exists zoho_do_not_push boolean not null default false;
alter table public.goods_receipt add column if not exists zoho_do_not_push boolean not null default false;
alter table public.zoho_config   add column if not exists dc text;        -- detected at token exchange

-- every Zoho document a CTP record corresponds to (one order can be several invoices)
create table if not exists public.zoho_doc_link (
  id          bigint generated by default as identity primary key,
  ctp_table   text not null check (ctp_table in ('sales_order','goods_receipt')),
  ctp_id      bigint not null,
  zoho_type   text not null check (zoho_type in ('invoice','creditnote','bill','purchaseorder')),
  zoho_id     text not null,
  zoho_number text not null,
  relation    text not null default 'imported',   -- imported | credited | pushed
  note        text,
  created_at  timestamptz not null default now(),
  unique (ctp_table, ctp_id, zoho_type, zoho_id)
);
alter table public.zoho_doc_link enable row level security;
drop policy if exists zoho_doc_link_staff_read on public.zoho_doc_link;
create policy zoho_doc_link_staff_read on public.zoho_doc_link for select to authenticated using (is_staff());
grant select on public.zoho_doc_link to authenticated;

-- the queue never offers a do-not-push document
create or replace view public.zoho_push_queue
with (security_invoker = true) as
  select 'invoice'::text as doc_type, so.id as ctp_id, so.invoice_no as ctp_ref,
         so.invoiced_at as doc_at, so.zoho_error as last_error
    from sales_order so, zoho_config c
   where so.status = 'invoiced' and so.deleted_at is null and not so.zoho_do_not_push
     and so.invoice_no is not null and so.zoho_invoice_id is null
     and c.push_from is not null and so.invoiced_at >= c.push_from
  union all
  select 'bill', gr.id, gr.number, gr.posted_at, gr.zoho_error
    from goods_receipt gr, zoho_config c
   where gr.status = 'posted' and gr.kind = 'purchase' and gr.deleted_at is null and not gr.zoho_do_not_push
     and gr.supplier_id is not null and gr.zoho_bill_id is null
     and c.push_from is not null and gr.posted_at >= c.push_from;

-- ── 1. the four historical Hermans orders ───────────────────────────────────
create temp table _hist (ctp_id bigint, ctp_number text, zoho_id text, zoho_number text, relation text, note text) on commit drop;
insert into _hist values
  (8, 'INV-26072403', '1429405000000268433', 'DS000009', 'imported', 'exact: PO 21261, 7 lines, R10 771.32 excl VAT'),
  (6, 'SO-1005',      '1429405000000268410', 'DS000001', 'imported', 'PO 21297; same parts (Multicat GI000001)'),
  (6, 'SO-1005',      '1429405000000268552', 'DS000002', 'imported', 'PO 21297; same parts (Multicat GI000002)'),
  (6, 'SO-1005',      '1429405000000268535', 'DS000003', 'imported', 'PO 21297; same parts (Multicat GI000003)'),
  (5, 'SO-1004',      '1429405000000268522', 'DS000004', 'imported', 'PO 21293; same parts (Multicat GI000004)'),
  (4, 'SO-1003',      '1429405000000268484', 'DS000006', 'imported', 'PO 21287; same parts (Multicat GI000006)'),
  (4, 'SO-1003',      '1429405000000268503', 'DS000005', 'credited', 'same 6 lines, credited in full by CN000001 (Multicat GI000005/GC000001)');

do $$
declare bad text;
begin
  select string_agg(h.ctp_number, ', ') into bad from _hist h
   where not exists (select 1 from sales_order so where so.id = h.ctp_id and so.number = h.ctp_number and so.deleted_at is null);
  if bad is not null then raise exception 'Historical order not found as expected: %', bad; end if;
end $$;

insert into zoho_doc_link (ctp_table, ctp_id, zoho_type, zoho_id, zoho_number, relation, note)
select 'sales_order', ctp_id, 'invoice', zoho_id, zoho_number, relation, note from _hist
on conflict do nothing;

update sales_order so
   set zoho_do_not_push = true,
       -- one Zoho id where the order is ONE invoice; SO-1005 is three, kept in zoho_doc_link
       zoho_invoice_id = case when x.n = 1 then x.zoho_id else so.zoho_invoice_id end,
       zoho_invoice_number = x.numbers,
       zoho_status = coalesce(so.zoho_status, 'historical'),
       zoho_error = null,
       notes = case when coalesce(so.notes, '') like '%Historical – imported%' then so.notes
                    else concat_ws(E'\n', nullif(so.notes, ''),
                         '[2026-10-19] Historical – imported into Zoho by the accountant as ' || x.numbers || '. Never pushed from CTP Core.') end,
       updated_at = now()
  from (select ctp_id, count(*) n, min(zoho_id) zoho_id, string_agg(zoho_number, ' + ' order by zoho_number) numbers
          from _hist where relation = 'imported' group by ctp_id) x
 where so.id = x.ctp_id;

-- ── 2 + 3. test orders out, their stock put back ────────────────────────────
create temp table _test on commit drop as
  select so.id from sales_order so join customer c on c.id = so.customer_id
   where c.code in ('GSLOGI', 'TESTACC')
     and so.id not in (select ctp_id from _hist);

insert into stock_movement (part_id, location_id, delta, reason, client_uuid, origin, actor_label, actor_source)
select m.part_id, m.location_id, -sum(m.delta), 'adjustment',
       'cleanup-0048-so-' || t.id || '-p' || m.part_id || '-l' || m.location_id,
       'mig0048', 'go-live tidy: test order removed', 'server_session'
  from _test t join stock_movement m on m.client_uuid like 'so-' || t.id || '-%'
 group by t.id, m.part_id, m.location_id
having sum(m.delta) <> 0
on conflict (client_uuid) do nothing;

update sales_order
   set deleted_at = coalesce(deleted_at, now()),
       zoho_do_not_push = true,
       notes = case when coalesce(notes, '') like '%go-live tidy%' then notes
                    else concat_ws(E'\n', nullif(notes, ''), '[2026-10-19] Removed in the go-live tidy: test data, not in Zoho. Stock effect reversed (0048).') end,
       updated_at = now()
 where id in (select id from _test);

update customer
   set deleted_at = now(), updated_at = now(),
       notes = concat_ws(E'\n', nullif(notes, ''), '[2026-10-19] Demo customer from the June seed, removed in the go-live tidy (0048).')
 where code in ('GSLOGI', 'HXFLEET', 'DESERTHL') and deleted_at is null;

-- ── 4. the Zoho token, in Vault ─────────────────────────────────────────────
create or replace function public.zoho_secret_put(p_name text, p_value text)
returns void language plpgsql security definer set search_path = public, vault, pg_temp as $$
declare v_id uuid;
begin
  if p_name not in ('zoho_refresh_token') then raise exception 'unknown secret %', p_name; end if;
  select id into v_id from vault.secrets where name = p_name;
  if v_id is null then perform vault.create_secret(p_value, p_name, 'Zoho Books OAuth refresh token (CTP Core)');
  else perform vault.update_secret(v_id, p_value); end if;
end $$;
create or replace function public.zoho_secret_get(p_name text)
returns text language sql security definer set search_path = public, vault, pg_temp as $$
  select decrypted_secret from vault.decrypted_secrets where name = p_name and p_name in ('zoho_refresh_token')
$$;
revoke all on function public.zoho_secret_put(text, text) from public, anon, authenticated;
revoke all on function public.zoho_secret_get(text) from public, anon, authenticated;
grant execute on function public.zoho_secret_put(text, text) to service_role;
grant execute on function public.zoho_secret_get(text) to service_role;

commit;

