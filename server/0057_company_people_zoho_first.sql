-- ============================================================================
--  CTP Core — companies and people, Zoho-first (0057, Phase 1 of docs/06)
--
--  Company = a Zoho Books customer contact. CTP Core's `customer` row is its
--  cache + link (zoho_contact_id), as since 0056.
--  Person  = a Zoho contact person on that contact. `customer_person` is its
--  cache + link (zoho_contact_person_id) + the one thing Zoho cannot hold:
--  which CTP Core login is this person (auth_user_id).
--
--  Name / email / phone here are a CACHE of Zoho, refreshed from Zoho; Zoho is
--  the master. Creating anything in Zoho happens in the zoho-company function,
--  after a preview, never from SQL.
--
--  Logins: the login -> company map now also runs through people, so a company
--  can have several people with logins. customer.auth_user_id (one login per
--  company, the old way) keeps working unchanged — the live test's Test Account
--  (Ian) login is backfilled as a person AND still works the old way.
--  No login is ever created here.
-- ============================================================================
begin;

create table if not exists public.customer_person (
  id                      bigint generated by default as identity primary key,
  customer_id             bigint not null references public.customer(id),
  zoho_contact_person_id  text unique,
  auth_user_id            uuid unique,
  first_name              text,          -- cache of Zoho
  last_name               text,          -- cache of Zoho
  email                   text,          -- cache of Zoho
  phone                   text,          -- cache of Zoho
  is_primary              boolean not null default false,
  rev                     integer not null default 1,
  created_at              timestamptz not null default now(),
  updated_at              timestamptz not null default now(),
  deleted_at              timestamptz,
  origin                  text
);
create index if not exists customer_person_customer_idx on public.customer_person (customer_id);

alter table public.customer_person enable row level security;
drop policy if exists customer_person_staff on public.customer_person;
create policy customer_person_staff on public.customer_person for all to authenticated
  using (is_staff()) with check (is_staff());
drop policy if exists customer_person_self on public.customer_person;
create policy customer_person_self on public.customer_person for select to authenticated
  using (auth_user_id = auth.uid());
grant select, insert, update on public.customer_person to authenticated;

-- billing address cache on the company (Zoho is the master)
alter table public.customer add column if not exists billing_address jsonb;

-- backfill: today's one-login-per-company becomes that company's first person
insert into public.customer_person (customer_id, auth_user_id, first_name, email, is_primary, origin)
select c.id, c.auth_user_id, coalesce(nullif(c.contact, ''), au.display_name, c.name), u.email, true, 'mig0057'
  from public.customer c
  left join public.app_user au on au.id = c.auth_user_id
  left join auth.users u on u.id = c.auth_user_id
 where c.auth_user_id is not null and c.deleted_at is null
   and not exists (select 1 from public.customer_person p where p.auth_user_id = c.auth_user_id);

-- the login -> company map: the old column first (unchanged behaviour), then people
create or replace function public.my_customer_id() returns bigint
language sql stable security definer set search_path = public as $$
  select coalesce(
    (select id from customer where auth_user_id = auth.uid() and deleted_at is null limit 1),
    (select p.customer_id from customer_person p join customer c on c.id = p.customer_id
      where p.auth_user_id = auth.uid() and p.deleted_at is null and c.deleted_at is null limit 1))
$$;

-- a login belongs to a company (for the server side: accept-quote)
create or replace function public.login_company(p_auth_user uuid) returns bigint
language sql stable security definer set search_path = public as $$
  select coalesce(
    (select id from customer where auth_user_id = p_auth_user and deleted_at is null limit 1),
    (select p.customer_id from customer_person p join customer c on c.id = p.customer_id
      where p.auth_user_id = p_auth_user and p.deleted_at is null and c.deleted_at is null limit 1))
$$;
revoke all on function public.login_company(uuid) from public, anon, authenticated;
grant execute on function public.login_company(uuid) to service_role;

-- a customer person sees their own company row too
drop policy if exists customer_self on public.customer;
create policy customer_self on public.customer for select to authenticated using (id = my_customer_id());

-- accept_quote (0054): ownership through the company, not only the old column
create or replace function public.accept_quote(order_id bigint, p_auth_user uuid, p_zoho_salesorder_id text, p_zoho_salesorder_number text)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v_o record; v_bad text; v_reserved int := 0; v_live boolean := zoho_live();
begin
  if auth.uid() is not null then
    raise exception 'accept_quote is called by the server, not from a session.' using errcode = '42501';
  end if;
  if v_live and coalesce(p_zoho_salesorder_id, '') = '' then
    raise exception 'accept_quote needs the Zoho sales order id (Zoho sending is on).' using errcode = '22023';
  end if;
  select so.id, so.number, so.status, so.customer_id, so.zoho_salesorder_id
    into v_o from sales_order so
   where so.id = accept_quote.order_id and so.deleted_at is null for update of so;
  if v_o.id is null then raise exception 'No such order.' using errcode = '42704'; end if;
  if login_company(p_auth_user) is distinct from v_o.customer_id then
    raise exception 'That order belongs to a different customer.' using errcode = '42501';
  end if;
  if v_o.status = 'confirmed' and v_o.zoho_salesorder_id is not distinct from nullif(p_zoho_salesorder_id, '') then
    return jsonb_build_object('order_id', v_o.id, 'number', v_o.number, 'status', 'confirmed',
                              'zoho_salesorder_number', p_zoho_salesorder_number, 'reserved_lines', 0, 'already', true);
  end if;
  if v_o.status <> 'quote' then
    raise exception '% is already %, so it cannot be accepted.', v_o.number, v_o.status using errcode = '22023';
  end if;
  select string_agg(p.name || ' (' || p.sku || ')', ', ') into v_bad
    from sales_line sl join part p on p.id = sl.part_id
   where sl.order_id = v_o.id and sl.deleted_at is null
     and (sl.unit_price_minor <= 0
          or (v_live and not exists (select 1 from zoho_item z where z.part_id = p.id and z.status <> 'inactive')));
  if v_bad is not null then
    raise exception 'This quote has a line that cannot be ordered yet: %', v_bad using errcode = '22023';
  end if;
  update sales_order
     set status = 'confirmed', client_response = 'accepted', client_responded_at = now(),
         zoho_salesorder_id = nullif(p_zoho_salesorder_id, ''), zoho_salesorder_number = nullif(p_zoho_salesorder_number, ''),
         zoho_created_at = case when coalesce(p_zoho_salesorder_id, '') <> '' then now() end,
         zoho_so_status = case when coalesce(p_zoho_salesorder_id, '') <> '' then 'draft' end,
         zoho_so_status_at = case when coalesce(p_zoho_salesorder_id, '') <> '' then now() end,
         zoho_so_error = null, updated_at = now()
   where id = v_o.id;
  v_reserved := public.reserve_order(v_o.id);
  return jsonb_build_object('order_id', v_o.id, 'number', v_o.number, 'status', 'confirmed',
                            'zoho_salesorder_number', nullif(p_zoho_salesorder_number, ''), 'reserved_lines', v_reserved,
                            'already', false, 'zoho_live', v_live);
end $$;
revoke all on function public.accept_quote(bigint, uuid, text, text) from public, anon, authenticated;
grant execute on function public.accept_quote(bigint, uuid, text, text) to service_role;

-- staff: which companies and people can be picked (cache rows, Zoho-linked first)
create or replace view public.company_directory with (security_invoker = true) as
  select c.id, c.code, c.name, c.email, c.vat_no, c.zoho_contact_id, c.billing_address,
         (select count(*) from customer_person p where p.customer_id = c.id and p.deleted_at is null) as people
    from customer c where c.deleted_at is null;
grant select on public.company_directory to authenticated;

commit;

select (select count(*) from customer_person) people, (select count(*) from customer_person where auth_user_id is not null) with_login;
