--
-- Ian chose B: re-apply the sheet's RULE to Zoho's CURRENT sales price and cost: rebate = the
-- highest of 25 / 20 / 15 / 10 / 0 % that keeps contribution margin ≥ 30 % after 10 % sales
-- commission, where contribution margin = (1 − commission) × (rebate price − cost) / rebate price.
-- Zoho item rates are never changed: the price book carries the rebate prices.
--   rebate_scheme      one per Zoho price book (name = the price book's name), with the rule.
--   rebate_scheme_sku  the parts in the scheme (from Ian's sheet of 24 Oct: 154 parts in Zoho;
--                      DIA001 is not a Zoho item).
-- zoho-push {action:"rebate_book", scheme, apply?} recomputes from Zoho's live price/cost and
-- (with apply) creates or updates that one price book. Re-run whenever prices or costs change.
-- Staff-only reads: the rule and cost-based results never reach customers.
begin;

create table if not exists public.rebate_scheme (
  id bigint generated by default as identity primary key,
  name text not null unique,
  tiers numeric[] not null default '{0.25,0.20,0.15,0.10,0}',
  min_contribution numeric not null default 0.30,
  commission numeric not null default 0.10,
  include_zero boolean not null default false,       -- 0 % parts: left out of the book (Zoho then uses the sales rate)
  zoho_pricebook_id text,
  last_built_at timestamptz,
  last_result jsonb,
  updated_at timestamptz not null default now()
);
create table if not exists public.rebate_scheme_sku (
  scheme_id bigint not null references public.rebate_scheme(id) on delete cascade,
  sku text not null,
  source text not null default 'sheet 2026-10-24',
  primary key (scheme_id, sku)
);
alter table public.rebate_scheme enable row level security;
alter table public.rebate_scheme_sku enable row level security;
drop policy if exists rebate_scheme_staff on public.rebate_scheme;
create policy rebate_scheme_staff on public.rebate_scheme for select to authenticated using (is_staff());
drop policy if exists rebate_scheme_sku_staff on public.rebate_scheme_sku;
create policy rebate_scheme_sku_staff on public.rebate_scheme_sku for select to authenticated using (is_staff());
revoke all on public.rebate_scheme, public.rebate_scheme_sku from anon;
grant select on public.rebate_scheme, public.rebate_scheme_sku to authenticated;

