#!/usr/bin/env python3
"""
Generate the "OEM / Multicat code is the item code" migrations, cloud and desktop,
from ONE data file so the two can never disagree:

    data/zoho_multicat_items_2026-10-19.csv
      old_sku, sku, zoho_item_id, name, rate_zar, landed_zar,
      zoho_purchase_rate_zar, qty_multicat, qty_basis

    -> server/0046_multicat_codes.sql                    (Postgres, SQL editor)
    -> app/src-tauri/migrations/0025_multicat_codes.sql  (desktop SQLite, v24)

Run from the repo root:

    python server/gen_0046_multicat_codes.py

The data file was built on 2026-10-19 from the "CTP Zoho Merge" working folder
(CTP_SKU_Mapping_Old_to_Multicat, CTP_Zoho_Items_IMPORT_v3, CTP_Item_Codes_for_
Michelle). Multicat is the source of truth: SKU = Multicat/OEM code, landed cost =
Multicat landed (= Zoho Purchase Rate), list price = Zoho Rate (Multicat average
sale where sold). Four items have no Rate in the files - they keep their current
CTP list price until the Zoho pull (server/edge/zoho-sync) supplies one.
"""
import csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
DATA = os.path.join(ROOT, "data", "zoho_multicat_items_2026-10-19.csv")
OUT_PG = os.path.join(HERE, "0046_multicat_codes.sql")
OUT_SQLITE = os.path.join(ROOT, "app", "src-tauri", "migrations", "0025_multicat_codes.sql")

VALID_FROM = "2026-10-19"
SOURCE = "Multicat landed = Zoho Purchase Rate, 2026-10-19"
PRICE_SOURCE = "Zoho Rate (Multicat avg sale), 2026-10-19"

# Old CTP parts the mapping file leaves blank. Each part's inventory_pn already
# carried the Multicat code, and Zoho has a NEW item for it (the four "held"
# matches resolved as option B). One rule per part, evidence alongside.
HELD = {
    # old sku         -> multicat code    (part name in CTP Core)
    "CTP-FND-006-L": "5103131-B45-G",   # Rear Fender L/H        inv_pn 5103131-B45-G
    "CTP-FND-007-R": "5103132-B45-G",   # Rear Fender R/H        inv_pn 5103132-B45-G
    "CTP-FWL-001-C": "5302021-B45-G",   # Front Wall Outer Panel inv_pn 5302021-B45-G
    "CTP-FWL-009-C": "5300010-H02-DQ",  # Front Wall Welding     inv_pn 5300010-H02-DQ
}

# Parts with no Multicat item of their own. Not deleted, not renamed: their
# status follows what Zoho now says about them.
DISCONTINUED = {
    "CTP-STP-005-R": "Zoho duplicate of Primary Step (5103031-1063) - inactivated 2026-10-19; sell CTP-STP-001-B / 5103031-1063",
    "CTP-CBY-001-C": "Cab Weld Assembly 5000040EB45 - not in Multicat, Zoho item inactivated 2026-10-19",
    "CTP-CBY-004-C": "Floor Assembly 5100010-H02 - not in Multicat, Zoho item inactivated 2026-10-19",
}
# Multicat merged the L/H and R/H rows into one "L/H or R/H" item. The R/H row
# here is superseded by the part that now carries the merged code.
SUPERSEDED = {
    "CTP-TBX-004-R": "CTP-TBX-003-L",   # Side Toolbox Sealing Strip -> 5407086-B45-C00
    "CTP-DOR-022-R": "CTP-DOR-021-L",   # Front Door Limiter         -> 6109015-B45-C00
}
# Left exactly as they are, flagged - each needs a Multicat code fix first.
FLAGGED = {
    "CTP-TBX-002-R": "Side Toolbox Cover R/H: Multicat code 5407025-B45 collides with the L/H cover. Needs its own Multicat code.",
    "CTP-CBY-002-C": "Cab Front Panel Inner Board shares Multicat code 5300010-H02-DQ with Front Wall Welding. Needs its own Multicat code.",
}

CAB001 = {"category_code": "CBY", "side": "C"}


def minor(z):
    return None if z in ("", None) else int(round(float(z) * 100))


def q(s):
    return "NULL" if s is None else "'" + str(s).replace("'", "''") + "'"


def n(v):
    return "NULL" if v is None else str(v)


rows = list(csv.DictReader(open(DATA, encoding="utf-8")))
assert len(rows) == 155, len(rows)
inv = {v: k for k, v in HELD.items()}
for r in rows:
    if not r["old_sku"] and r["sku"] in inv:
        r["old_sku"] = inv[r["sku"]]
assert len({r["sku"] for r in rows}) == 155
staged = [r for r in rows if r["old_sku"]]
new_only = [r for r in rows if not r["old_sku"]]
assert [r["sku"] for r in new_only] == ["CAB001"], new_only

values = ",\n".join(
    f"  ({q(r['old_sku'] or None)}, {q(r['sku'])}, {q(r['zoho_item_id'])}, {q(r['name'])}, "
    f"{n(minor(r['rate_zar']))}, {n(minor(r['landed_zar']))})"
    for r in rows)

HEADER = """-- ============================================================================
--  CTP Core - THE OEM / MULTICAT CODE IS THE ITEM CODE  ({tag})
--  GENERATED by server/gen_0046_multicat_codes.py from
--  data/zoho_multicat_items_2026-10-19.csv - edit those, not this file.
--
--  Ian's decision, 2026-10-19: CTP Core shows OEM numbers. part.sku becomes the
--  Multicat/OEM code - the same string as the Zoho SKU - everywhere. The old
--  CTP-xxx code is kept as a LEGACY ALIAS only: a part_xref row
--  (xref_type 'supersession', xref_brand 'CTP legacy'), which every part search
--  already covers, so typing CTP-BMP-001-L still finds the part.
--
--  Also, from the same Multicat/Zoho alignment:
--    * part.name          <- Zoho/Multicat item name
--    * part_cost  ZAR     <- Multicat landed cost      (valid_from {vf})
--    * price list ZAR     <- Zoho Rate                 (valid_from {vf}; 151 of 155)
--    * part.list_price_minor <- the same Rate
--    * CAB001 (FAW Original Furnished CAB - Complete) is added
--    * 3 parts discontinued, 2 superseded, 2 flagged (see the generator)
--
--  NOT TOUCHED: the stock ledger (stock_movement), sales orders and lines,
--  images, hotspots, locators, catalogue_pn. Part ids do not change, so every
--  order line, photo and diagram marker stays attached to the same part.
--
--  Idempotent: a second run changes nothing.
-- ============================================================================
"""

# ---------------------------------------------------------------- Postgres ---
pg = HEADER.format(tag="Postgres 0046", vf=VALID_FROM) + f"""
begin;

create temp table _mc (
  old_sku text, sku text primary key, zoho_item_id text, name text,
  rate_minor bigint, landed_minor bigint
) on commit drop;

insert into _mc (old_sku, sku, zoho_item_id, name, rate_minor, landed_minor) values
{values};

-- 0. Refuse to run into a collision: a target code already held by a part
--    that is NOT the one being renamed onto it.
do $$
declare v text;
begin
  select string_agg(p.sku, ', ') into v
    from part p join _mc m on p.sku = m.sku
   where m.old_sku is not null
     and exists (select 1 from part o where o.sku = m.old_sku and o.id <> p.id);
  if v is not null then
    raise exception 'Multicat code already used by another part: %', v;
  end if;
end $$;

-- 1. Legacy alias, written BEFORE the rename while the old code is still on the part.
insert into part_xref (part_id, xref_number, xref_brand, xref_type, confidence, origin)
select p.id, p.sku, 'CTP legacy', 'supersession', 100, 'mig0046'
  from part p join _mc m on p.sku = m.old_sku
on conflict (part_id, xref_number, xref_type) do nothing;

-- 2. The rename. Name follows Zoho/Multicat.
update part p
   set sku = m.sku, name = m.name, updated_at = now()
  from _mc m
 where p.sku = m.old_sku;

-- 3. CAB001 - in Multicat and Zoho, never in CTP Core.
insert into part (id, sku, category_id, name, make, model, catalogue_pn, inventory_pn,
                  side, status, match_status, notes, origin)
select (select max(id) + 1 from part), 'CAB001',
       (select id from category where code = '{CAB001["category_code"]}'),
       'FAW Original Furnished CAB - Complete', 'FAW', 'JH6', 'CAB001', 'CAB001',
       '{CAB001["side"]}', 'active', 'MATCHED', 'Added 2026-10-19 from Multicat (GR000004).', 'mig0046'
 where not exists (select 1 from part where sku = 'CAB001');

-- 4. Landed cost, ZAR.
insert into part_cost (part_id, currency, amount_minor, valid_from, source, basis, origin)
select p.id, 'ZAR', m.landed_minor, timestamptz '{VALID_FROM}', '{SOURCE}', 'landed', 'mig0046'
  from _mc m join part p on p.sku = m.sku
 where m.landed_minor is not null
on conflict (part_id, currency, valid_from)
  do update set amount_minor = excluded.amount_minor, source = excluded.source,
                basis = excluded.basis, updated_at = now();

-- 5. Selling (list) price, ZAR - where Zoho has one.
insert into price (part_id, tier, currency, amount_minor, valid_from, origin)
select p.id, 'list', 'ZAR', m.rate_minor, timestamptz '{VALID_FROM}', 'mig0046'
  from _mc m join part p on p.sku = m.sku
 where m.rate_minor is not null
on conflict (part_id, tier, currency, valid_from)
  do update set amount_minor = excluded.amount_minor, updated_at = now();

update part p set list_price_minor = m.rate_minor, updated_at = now()
  from _mc m
 where p.sku = m.sku and m.rate_minor is not null
   and p.list_price_minor is distinct from m.rate_minor;

-- 6. Parts with no Multicat item of their own.
"""
for sku, why in DISCONTINUED.items():
    pg += (f"update part set status = 'discontinued', notes = concat_ws(' | ', nullif(notes, ''), {q(why)}), "
           f"updated_at = now() where sku = {q(sku)} and status <> 'discontinued';\n")
for sku, by in SUPERSEDED.items():
    pg += (f"update part set status = 'superseded', superseded_by = "
           f"(select part_id from part_xref where xref_number = {q(by)} and xref_type = 'supersession' limit 1), "
           f"notes = concat_ws(' | ', nullif(notes, ''), 'Multicat merged L/H and R/H into one item (was {by}) 2026-10-19'), "
           f"updated_at = now() where sku = {q(sku)} and status <> 'superseded';\n")
for sku, why in FLAGGED.items():
    pg += (f"update part set notes = concat_ws(' | ', nullif(notes, ''), {q('FLAG 2026-10-19: ' + why)}), updated_at = now() "
           f"where sku = {q(sku)} and coalesce(notes, '') not like '%FLAG 2026-10-19%';\n")

pg += f"""
-- 7. The Zoho link. One row per Zoho item; the zoho-sync edge function keeps
--    rate / purchase_rate / stock_on_hand current from the Zoho API. Zoho's
--    stock is a MIRROR - it is never written into the stock_movement ledger.
create table if not exists public.zoho_item (
  zoho_item_id        text primary key,
  part_id             bigint references public.part(id) on delete set null,
  sku                 text not null,
  name                text,
  status              text,
  rate_minor          bigint,
  purchase_rate_minor bigint,
  stock_on_hand       numeric,
  available_stock     numeric,
  zoho_updated_at     timestamptz,
  synced_at           timestamptz not null default now()
);
create index if not exists zoho_item_part_idx on public.zoho_item(part_id);
create index if not exists zoho_item_sku_idx  on public.zoho_item(sku);
alter table public.zoho_item enable row level security;
drop policy if exists zoho_item_staff_read on public.zoho_item;
create policy zoho_item_staff_read on public.zoho_item for select to authenticated using (is_staff());
grant select on public.zoho_item to authenticated;

create table if not exists public.zoho_sync_run (
  id          bigint generated by default as identity primary key,
  started_at  timestamptz not null default now(),
  finished_at timestamptz,
  ok          boolean,
  items_seen  integer,
  linked      integer,
  unmatched   jsonb,
  error       text,
  actor       uuid
);
alter table public.zoho_sync_run enable row level security;
drop policy if exists zoho_sync_run_staff_read on public.zoho_sync_run;
create policy zoho_sync_run_staff_read on public.zoho_sync_run for select to authenticated using (is_staff());
grant select on public.zoho_sync_run to authenticated;

insert into zoho_item (zoho_item_id, part_id, sku, name, status, rate_minor, purchase_rate_minor, synced_at)
select m.zoho_item_id, p.id, m.sku, m.name, 'active', m.rate_minor, m.landed_minor, timestamptz '{VALID_FROM}'
  from _mc m left join part p on p.sku = m.sku
 where m.zoho_item_id <> ''
on conflict (zoho_item_id) do update set part_id = excluded.part_id, sku = excluded.sku;

-- 8. Check, inside the transaction: every one of the 155 codes is a live part.
do $$
declare missing text;
begin
  select string_agg(m.sku, ', ') into missing
    from _mc m left join part p on p.sku = m.sku and p.deleted_at is null
   where p.id is null;
  if missing is not null then
    raise exception 'After 0046 these Multicat codes have no part: %', missing;
  end if;
end $$;

commit;

-- VERIFY (run after; the editor only shows the last SELECT):
select
  (select count(*) from part where deleted_at is null and status = 'active')               as active_parts,
  (select count(*) from part where deleted_at is null and status = 'active' and sku like 'CTP-%') as active_still_ctp_coded,
  (select count(*) from part_xref where xref_brand = 'CTP legacy')                          as legacy_aliases,
  (select count(*) from part_cost where valid_from = timestamptz '{VALID_FROM}')           as costs_19oct,
  (select count(*) from price where tier = 'list' and valid_from = timestamptz '{VALID_FROM}') as prices_19oct,
  (select count(*) from zoho_item where part_id is not null)                               as zoho_linked;
-- expect: active_still_ctp_coded = 1 (CTP-TBX-002-R, flagged) or 2 if CTP-CBY-002-C is still live;
--         legacy_aliases = 154, costs_19oct = 155, prices_19oct = 151, zoho_linked = 155
"""

# ---------------------------------------------------------------- SQLite ---
sq = HEADER.format(tag="desktop SQLite 0025 / user_version 24", vf=VALID_FROM) + f"""
-- WHY THE DESKTOP NEEDS ITS OWN COPY: the desktop pull (src/sync.rs) upserts
-- parts BY SKU. If only the cloud renamed, the next pull would add 151 "new"
-- parts beside the old CTP-coded ones. Renaming locally first makes the pull
-- land on the same rows. Runs inside the migration runner's batch.

CREATE TEMP TABLE _mc (
  old_sku TEXT, sku TEXT PRIMARY KEY, zoho_item_id TEXT, name TEXT,
  rate_minor INTEGER, landed_minor INTEGER
);
INSERT INTO _mc (old_sku, sku, zoho_item_id, name, rate_minor, landed_minor) VALUES
{values};

-- Skip any rename that would collide with an existing, different part (the
-- cloud migration refuses outright; the desktop must not refuse to start).
DELETE FROM _mc WHERE old_sku IS NOT NULL AND EXISTS (
  SELECT 1 FROM part p WHERE p.sku = _mc.sku
     AND p.id <> COALESCE((SELECT o.id FROM part o WHERE o.sku = _mc.old_sku), -1));

INSERT OR IGNORE INTO part_xref (part_id, xref_number, xref_brand, xref_type, confidence)
SELECT p.id, p.sku, 'CTP legacy', 'supersession', 100
  FROM part p JOIN _mc m ON p.sku = m.old_sku;

UPDATE part SET
  name = (SELECT m.name FROM _mc m WHERE m.old_sku = part.sku),
  sku  = (SELECT m.sku  FROM _mc m WHERE m.old_sku = part.sku),
  updated_at = datetime('now')
 WHERE sku IN (SELECT old_sku FROM _mc WHERE old_sku IS NOT NULL);

INSERT INTO part (id, sku, category_id, name, make, model, catalogue_pn, inventory_pn,
                  side, status, match_status, notes)
SELECT (SELECT MAX(id) + 1 FROM part), 'CAB001',
       (SELECT id FROM category WHERE code = '{CAB001["category_code"]}'),
       'FAW Original Furnished CAB - Complete', 'FAW', 'JH6', 'CAB001', 'CAB001',
       '{CAB001["side"]}', 'active', 'MATCHED', 'Added 2026-10-19 from Multicat (GR000004).'
 WHERE NOT EXISTS (SELECT 1 FROM part WHERE sku = 'CAB001')
   AND EXISTS (SELECT 1 FROM category WHERE code = '{CAB001["category_code"]}');

INSERT OR REPLACE INTO part_cost (part_id, currency, amount_minor, valid_from, source, basis)
SELECT p.id, 'ZAR', m.landed_minor, '{VALID_FROM}', '{SOURCE}', 'landed'
  FROM _mc m JOIN part p ON p.sku = m.sku
 WHERE m.landed_minor IS NOT NULL;

INSERT OR REPLACE INTO price (part_id, tier, currency, amount_minor, valid_from)
SELECT p.id, 'list', 'ZAR', m.rate_minor, '{VALID_FROM}'
  FROM _mc m JOIN part p ON p.sku = m.sku
 WHERE m.rate_minor IS NOT NULL;

UPDATE part SET list_price_minor = (SELECT m.rate_minor FROM _mc m WHERE m.sku = part.sku)
 WHERE sku IN (SELECT sku FROM _mc WHERE rate_minor IS NOT NULL);

"""
for sku, why in DISCONTINUED.items():
    sq += (f"UPDATE part SET status = 'discontinued', notes = TRIM(COALESCE(notes || ' | ', '') || {q(why)}) "
           f"WHERE sku = {q(sku)} AND status <> 'discontinued';\n")
for sku, by in SUPERSEDED.items():
    sq += (f"UPDATE part SET status = 'superseded', superseded_by = (SELECT part_id FROM part_xref "
           f"WHERE xref_number = {q(by)} AND xref_type = 'supersession' LIMIT 1), "
           f"notes = TRIM(COALESCE(notes || ' | ', '') || 'Multicat merged L/H and R/H into one item (was {by}) 2026-10-19') "
           f"WHERE sku = {q(sku)} AND status <> 'superseded';\n")
for sku, why in FLAGGED.items():
    sq += (f"UPDATE part SET notes = TRIM(COALESCE(notes || ' | ', '') || {q('FLAG 2026-10-19: ' + why)}) "
           f"WHERE sku = {q(sku)} AND COALESCE(notes, '') NOT LIKE '%FLAG 2026-10-19%';\n")
sq += "\nDROP TABLE _mc;\n"

for path, body in ((OUT_PG, pg), (OUT_SQLITE, sq)):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)
    print("wrote", os.path.relpath(path, ROOT), len(body.splitlines()), "lines")
print("renames", len(staged), "| new", len(new_only), "| priced", sum(1 for r in rows if r["rate_zar"]))
