-- CTP Core 0079 — onboarding a new make / model / brand, data-driven (26 Oct 2026, docs/13).
--
-- Ian: "replicate everything we've done with the FAW JH6 to any and every other make, model …
-- Sonnet truck next, as well as mechanical for all, and a lot more brands to come."
--
-- ADDITIVE ONLY. Nothing existing changes meaning; FAW JH6 behaves exactly as before.
--   * make_profile    — one row per make/model (or "All makes"): Zoho Manufacturer/Brand, Zoho GL
--                       accounts, default part type, rebate scheme, part-number pattern, lookup URL.
--                       The FAW JH6 row records what was hardcoded until now.
--   * part.universal  — "mechanical for all": fits every make, needs no fitment rows.
--   * part_type       — + 'Universal'.   part_xref.xref_type — + 'alternate'.
--   * vehicle_model   — + model years, engine, notes (fitment keeps its own years).
--   * part_supplier   — many suppliers per part (part.supplier stays the preferred one, as text).
--   * import_batch / import_batch_row — every row an onboarding import created or changed, with the
--                       row as it was before, so a batch can be rolled back (and a TEST batch purged).
--   * onboard_import(payload, dry_run) — validates and upserts a whole make in ONE transaction;
--                       dry run = the same work, then rolled back, returning what it would do.
--   * onboard_rollback(batch, purge, dry_run) — undoes a batch: restores updated rows, soft-deletes
--                       created ones (purge: hard-deletes them; only for TEST batches).
-- Server only (service role): the import is run by tools/onboard/onboard.py.
-- Sync rules: NO change. The new tables are server-side; part.universal rides along in part rows.
begin;

-- ── config: one row per make/model ───────────────────────────────────────────
create table if not exists public.make_profile (
  id bigint generated by default as identity primary key,
  code text not null unique check (code ~ '^[A-Z0-9_]{2,20}$'),   -- FAWJH6, SONNET_X, UNIVERSAL
  make text not null,                        -- vehicle make as CTP shows it (part.make)
  model text not null default '',            -- vehicle model (part.model); '' = all models / universal
  display_name text,
  parts_brand_code text,                     -- brand.code of the parts' maker (FAW = OEM)
  zoho_manufacturer text,                    -- Zoho item "Manufacturer"
  zoho_brand text,                           -- Zoho item "Brand"
  zoho_sales_account_id text,                -- Zoho GL: "Sales - FAW" …
  zoho_purchase_account_id text,             -- "Cost of Goods Sold - FAW" …
  zoho_inventory_account_id text,            -- "Inventory Asset"
  unit text not null default 'pcs',
  default_part_type text check (default_part_type is null or default_part_type in ('OEM', 'Aftermarket', 'Universal')),
  rebate_scheme_id bigint references public.rebate_scheme(id),
  pn_pattern text,                           -- regex a part number of this make should match (warning only)
  lookup_url text,                           -- supplier lookup, {pn} = part number
  description_template text not null default '{make} {model} · part no. {sku}',
  is_test boolean not null default false,
  active boolean not null default true,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (make, model)
);
alter table public.make_profile enable row level security;
revoke all on public.make_profile from anon, authenticated;

insert into public.make_profile (code, make, model, display_name, parts_brand_code, zoho_manufacturer, zoho_brand,
  zoho_sales_account_id, zoho_purchase_account_id, zoho_inventory_account_id, default_part_type, rebate_scheme_id,
  pn_pattern, lookup_url, notes)
select 'FAWJH6', 'FAW', 'JH6', 'FAW JH6', 'FAW', 'FAW', 'JH6',
       '1429405000000000391', '1429405000000034003', '1429405000000034001', 'OEM',
       (select id from public.rebate_scheme where name = 'FAW JH6 – Rebate'),
       '^[0-9]{4,}[A-Z0-9-]*$', 'https://www.google.com/search?q=site:rusauto43.ru+{pn}',
       'What was hardcoded for FAW JH6 until 0079 (Zoho accounts read from item 2801070-1063, 26 Oct).'
