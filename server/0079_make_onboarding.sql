-- ── the import ───────────────────────────────────────────────────────────────
-- Identity counters can be behind: 0066 (zoho_new_part) and older seeds insert explicit ids
-- (max+1). Before inserting, move each counter past the highest id — forward only, never back.
create or replace function public.onboard_bump_ids()
returns void language plpgsql security definer set search_path = public, pg_temp as $$
declare t text; s text; m bigint; lv bigint; ic boolean;
begin
  foreach t in array array['part', 'price', 'category', 'diagram', 'hotspot', 'part_image', 'part_xref', 'part_fitment',
                           'vehicle_model', 'brand', 'supplier', 'part_supplier', 'make_profile'] loop
    s := pg_get_serial_sequence('public.' || t, 'id');
    if s is null then continue; end if;
    execute format('select coalesce(max(id), 0) from public.%I', t) into m;
    execute format('select last_value, is_called from %s', s) into lv, ic;
    if m >= (case when ic then lv + 1 else lv end) then perform setval(s, m, true); end if;
  end loop;
end $$;
revoke all on function public.onboard_bump_ids() from public, anon, authenticated;

-- p: { batch, is_test, profile:{…make_profile cols}, brand:{code,name,is_oem}, vehicles:[{model,variant,year_from,
--      year_to,engine,notes}], sections:[{code,name}], suppliers:[{code,name,…}], parts:[{sku,name,section_code,
--      part_type,universal,make,model,catalogue_pn,mpn,side,drawing_no,diagram_item_no,description,uom,weight_g,
--      list_price_minor,supplier}], fitment:[{sku,make,model,variant,year_from,year_to,engine,note}],
--      xrefs:[{sku,xref_number,xref_brand,xref_type,confidence}], part_suppliers:[{sku,supplier_code,supplier_sku,
--      cost_minor,currency,lead_time_days,moq,is_preferred}], diagrams:[{drawing_key,section_code,title,image_path,
--      img_w,img_h}], hotspots:[{drawing_key,item_no,sku,x,y,radius}], images:[{sku,path,is_primary,sort_order,caption}],
--      scheme_skus:[{scheme,sku}] }
create or replace function public.onboard_import(p jsonb, p_dry_run boolean default true)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_batch text := btrim(coalesce(p->>'batch', ''));
  v_test boolean := coalesce((p->>'is_test')::boolean, false);
  pr jsonb := coalesce(p->'profile', '{}'::jsonb);
  v_make text := btrim(coalesce(pr->>'make', ''));
  v_model text := btrim(coalesce(pr->>'model', ''));
  v_brand_id bigint; v_id bigint; v_old jsonb; v_cat bigint; v_veh bigint; v_part bigint; v_dg bigint; v_sup bigint; v_sch bigint;
  r jsonb; v_errors text[] := '{}'; v_warn text[] := '{}';
  c jsonb := '{}'::jsonb;   -- counts: entity -> {created, updated, unchanged}
  v_result jsonb;
begin
  if auth.uid() is not null then
    raise exception 'onboard_import is run by the server (tools/onboard), not from a session.' using errcode = '42501';
  end if;
  if v_batch !~ '^[A-Za-z0-9_.-]{3,60}$' then raise exception 'batch code missing or invalid: %', v_batch; end if;
  if coalesce(pr->>'code', '') = '' or v_make = '' then raise exception 'profile.code and profile.make are required'; end if;
  if exists (select 1 from import_batch where code = v_batch and status <> 'imported') then
    raise exception 'batch % was rolled back — use a new batch code', v_batch;
  end if;

  perform onboard_bump_ids();
  begin   -- everything below is one subtransaction: a dry run (or any error) undoes all of it
    insert into import_batch (code, profile_code, is_test) values (v_batch, pr->>'code', v_test)
      on conflict (code) do update set updated_at = now();

    -- small helper semantics, inlined: record a created / updated row
    -- profile
    select to_jsonb(m), m.id into v_old, v_id from make_profile m where m.code = pr->>'code';
    if v_id is null then
      insert into make_profile (code, make, model, display_name, parts_brand_code, zoho_manufacturer, zoho_brand,
        zoho_sales_account_id, zoho_purchase_account_id, zoho_inventory_account_id, unit, default_part_type,
        rebate_scheme_id, pn_pattern, lookup_url, description_template, is_test, notes)
      values (pr->>'code', v_make, v_model, pr->>'display_name', nullif(pr->>'parts_brand_code', ''),
        nullif(pr->>'zoho_manufacturer', ''), nullif(pr->>'zoho_brand', ''), nullif(pr->>'zoho_sales_account_id', ''),
        nullif(pr->>'zoho_purchase_account_id', ''), nullif(pr->>'zoho_inventory_account_id', ''), coalesce(nullif(pr->>'unit', ''), 'pcs'),
        nullif(pr->>'default_part_type', ''), (select id from rebate_scheme where name = pr->>'rebate_scheme'),
        nullif(pr->>'pn_pattern', ''), nullif(pr->>'lookup_url', ''),
        coalesce(nullif(pr->>'description_template', ''), '{make} {model} · part no. {sku}'), v_test, pr->>'notes')
      returning id into v_id;
      insert into import_batch_row (batch_code, entity, row_id, row_key, action) values (v_batch, 'make_profile', v_id, pr->>'code', 'created');
      c := jsonb_set(c, '{make_profile}', '{"created":1}');
    else
      if (v_old->>'make') is distinct from v_make or (v_old->>'model') is distinct from v_model then
        v_errors := v_errors || format('profile %s already exists for %s %s — not %s %s', pr->>'code', v_old->>'make', v_old->>'model', v_make, v_model);
      end if;
      update make_profile set display_name = coalesce(pr->>'display_name', display_name),
        parts_brand_code = coalesce(nullif(pr->>'parts_brand_code', ''), parts_brand_code),
        zoho_manufacturer = coalesce(nullif(pr->>'zoho_manufacturer', ''), zoho_manufacturer),
        zoho_brand = coalesce(nullif(pr->>'zoho_brand', ''), zoho_brand),
        zoho_sales_account_id = coalesce(nullif(pr->>'zoho_sales_account_id', ''), zoho_sales_account_id),
        zoho_purchase_account_id = coalesce(nullif(pr->>'zoho_purchase_account_id', ''), zoho_purchase_account_id),
        zoho_inventory_account_id = coalesce(nullif(pr->>'zoho_inventory_account_id', ''), zoho_inventory_account_id),
        default_part_type = coalesce(nullif(pr->>'default_part_type', ''), default_part_type),
        rebate_scheme_id = coalesce((select id from rebate_scheme where name = pr->>'rebate_scheme'), rebate_scheme_id),
        pn_pattern = coalesce(nullif(pr->>'pn_pattern', ''), pn_pattern), lookup_url = coalesce(nullif(pr->>'lookup_url', ''), lookup_url),
        updated_at = now()
      where id = v_id;
      if (select to_jsonb(m) - 'updated_at' from make_profile m where id = v_id) is distinct from (v_old - 'updated_at') then
        insert into import_batch_row (batch_code, entity, row_id, row_key, action, before) values (v_batch, 'make_profile', v_id, pr->>'code', 'updated', v_old);
        c := jsonb_set(c, '{make_profile}', '{"updated":1}');
      end if;
    end if;
    if coalesce(pr->>'rebate_scheme', '') <> '' and not exists (select 1 from rebate_scheme where name = pr->>'rebate_scheme') then
      v_errors := v_errors || format('rebate scheme "%s" does not exist in CTP', pr->>'rebate_scheme');
    end if;

    -- parts brand (who makes the parts)
    if coalesce(p->'brand'->>'code', '') <> '' then
      select id into v_brand_id from brand where code = p->'brand'->>'code';
      if v_brand_id is null then
        insert into brand (code, name, is_oem) values (p->'brand'->>'code', coalesce(p->'brand'->>'name', p->'brand'->>'code'),
          coalesce((p->'brand'->>'is_oem')::int, 0)) returning id into v_brand_id;
        insert into import_batch_row (batch_code, entity, row_id, row_key, action) values (v_batch, 'brand', v_brand_id, p->'brand'->>'code', 'created');
      end if;
    end if;

    -- vehicles (make from the profile)
    for r in select * from jsonb_array_elements(coalesce(p->'vehicles', '[]')) loop
      select id, to_jsonb(v) into v_veh, v_old from vehicle_model v
       where make = coalesce(nullif(r->>'make', ''), v_make) and model = coalesce(nullif(r->>'model', ''), v_model)
         and coalesce(variant, '') = coalesce(r->>'variant', '');
      if v_veh is null then
        insert into vehicle_model (make, model, variant, year_from, year_to, engine, notes)
        values (coalesce(nullif(r->>'make', ''), v_make), coalesce(nullif(r->>'model', ''), v_model), coalesce(r->>'variant', ''),
                nullif(r->>'year_from', '')::int, nullif(r->>'year_to', '')::int, nullif(r->>'engine', ''), nullif(r->>'notes', ''))
        returning id into v_veh;
        insert into import_batch_row (batch_code, entity, row_id, row_key, action) values (v_batch, 'vehicle_model', v_veh, r::text, 'created');
      else
        update vehicle_model set year_from = coalesce(nullif(r->>'year_from', '')::int, year_from), year_to = coalesce(nullif(r->>'year_to', '')::int, year_to),
               engine = coalesce(nullif(r->>'engine', ''), engine), notes = coalesce(nullif(r->>'notes', ''), notes)
         where id = v_veh and (year_from, year_to, engine, notes) is distinct from
               (coalesce(nullif(r->>'year_from', '')::int, year_from), coalesce(nullif(r->>'year_to', '')::int, year_to),
                coalesce(nullif(r->>'engine', ''), engine), coalesce(nullif(r->>'notes', ''), notes));
        if found then insert into import_batch_row (batch_code, entity, row_id, row_key, action, before) values (v_batch, 'vehicle_model', v_veh, r::text, 'updated', v_old); end if;
      end if;
    end loop;

    -- sections (= categories; shared across makes, created when new)
    for r in select * from jsonb_array_elements(coalesce(p->'sections', '[]')) loop
      if not exists (select 1 from category where code = r->>'code') then
        insert into category (code, name, path) values (r->>'code', r->>'name', r->>'name') returning id into v_id;
        insert into import_batch_row (batch_code, entity, row_id, row_key, action) values (v_batch, 'category', v_id, r->>'code', 'created');
      end if;
    end loop;

    -- suppliers
    for r in select * from jsonb_array_elements(coalesce(p->'suppliers', '[]')) loop
      if not exists (select 1 from supplier where code = r->>'code') then
        insert into supplier (code, name, contact, phone, email, currency, lead_time_days, vat_no, notes)
        values (r->>'code', r->>'name', nullif(r->>'contact', ''), nullif(r->>'phone', ''), nullif(r->>'email', ''),
                coalesce(nullif(r->>'currency', ''), 'ZAR'), nullif(r->>'lead_time_days', '')::int, nullif(r->>'vat_no', ''), nullif(r->>'notes', ''))
        returning id into v_id;
        insert into import_batch_row (batch_code, entity, row_id, row_key, action) values (v_batch, 'supplier', v_id, r->>'code', 'created');
      end if;
    end loop;

    -- parts (by SKU). An existing part of ANOTHER make is never touched: that is an error.
    for r in select * from jsonb_array_elements(coalesce(p->'parts', '[]')) loop
      select id into v_cat from category where code = r->>'section_code';
      if v_cat is null then v_errors := v_errors || format('%s: section %s unknown', r->>'sku', r->>'section_code'); continue; end if;
      select id, to_jsonb(x) into v_part, v_old from part x where upper(btrim(sku)) = upper(btrim(r->>'sku')) and deleted_at is null;
      if v_part is null then
        insert into part (sku, name, category_id, part_type, universal, make, model, catalogue_pn, mpn, side, drawing_no, diagram_item_no,
                          description, uom, weight_g, brand_id, list_price_minor, supplier, status, notes)
        values (btrim(r->>'sku'), r->>'name', v_cat, coalesce(nullif(r->>'part_type', ''), nullif(pr->>'default_part_type', '')),
                coalesce((r->>'universal')::boolean, false),
                case when coalesce((r->>'universal')::boolean, false) then coalesce(nullif(r->>'make', ''), v_make) else coalesce(nullif(r->>'make', ''), v_make) end,
                coalesce(nullif(r->>'model', ''), nullif(v_model, '')),
                nullif(r->>'catalogue_pn', ''), nullif(r->>'mpn', ''), nullif(r->>'side', ''), nullif(r->>'drawing_no', ''),
                nullif(r->>'diagram_item_no', '')::int, nullif(r->>'description', ''), coalesce(nullif(r->>'uom', ''), 'EA'),
                nullif(r->>'weight_g', '')::int, v_brand_id, nullif(r->>'list_price_minor', '')::int, nullif(r->>'supplier', ''), 'active',
                nullif(r->>'notes', ''))
        returning id into v_part;
        insert into import_batch_row (batch_code, entity, row_id, row_key, action) values (v_batch, 'part', v_part, r->>'sku', 'created');
        if nullif(r->>'list_price_minor', '') is not null then
          insert into price (part_id, tier, currency, amount_minor, valid_from) values (v_part, 'list', 'ZAR', (r->>'list_price_minor')::int, now())
          returning id into v_id;
          insert into import_batch_row (batch_code, entity, row_id, row_key, action) values (v_batch, 'price', v_id, r->>'sku', 'created');
        end if;
        c := jsonb_set(c, '{parts_created}', to_jsonb(coalesce((c->>'parts_created')::int, 0) + 1));
      else
        if (v_old->>'make') is distinct from coalesce(nullif(r->>'make', ''), v_make) then
          v_errors := v_errors || format('%s already exists as a %s part — another make''s part is never overwritten', r->>'sku', coalesce(v_old->>'make', 'no-make'));
          continue;
        end if;
        update part set name = r->>'name', category_id = v_cat,
          part_type = coalesce(nullif(r->>'part_type', ''), part_type), universal = coalesce((r->>'universal')::boolean, universal),
          model = coalesce(nullif(r->>'model', ''), model), catalogue_pn = coalesce(nullif(r->>'catalogue_pn', ''), catalogue_pn),
          mpn = coalesce(nullif(r->>'mpn', ''), mpn), side = coalesce(nullif(r->>'side', ''), side),
          drawing_no = coalesce(nullif(r->>'drawing_no', ''), drawing_no), diagram_item_no = coalesce(nullif(r->>'diagram_item_no', '')::int, diagram_item_no),
          description = coalesce(nullif(r->>'description', ''), description), weight_g = coalesce(nullif(r->>'weight_g', '')::int, weight_g),
          brand_id = coalesce(v_brand_id, brand_id), supplier = coalesce(nullif(r->>'supplier', ''), supplier)
        where id = v_part
          and (name, category_id, part_type, universal, model, catalogue_pn, mpn, side, drawing_no, diagram_item_no, description, weight_g, brand_id, supplier)
              is distinct from
              (r->>'name', v_cat, coalesce(nullif(r->>'part_type', ''), part_type), coalesce((r->>'universal')::boolean, universal),
               coalesce(nullif(r->>'model', ''), model), coalesce(nullif(r->>'catalogue_pn', ''), catalogue_pn), coalesce(nullif(r->>'mpn', ''), mpn),
               coalesce(nullif(r->>'side', ''), side), coalesce(nullif(r->>'drawing_no', ''), drawing_no),
               coalesce(nullif(r->>'diagram_item_no', '')::int, diagram_item_no), coalesce(nullif(r->>'description', ''), description),
               coalesce(nullif(r->>'weight_g', '')::int, weight_g), coalesce(v_brand_id, brand_id), coalesce(nullif(r->>'supplier', ''), supplier));
        if found then
          insert into import_batch_row (batch_code, entity, row_id, row_key, action, before) values (v_batch, 'part', v_part, r->>'sku', 'updated', v_old);
          c := jsonb_set(c, '{parts_updated}', to_jsonb(coalesce((c->>'parts_updated')::int, 0) + 1));
        end if;
        -- prices of an existing part are Zoho's (master): never changed here, only reported
        if nullif(r->>'list_price_minor', '') is not null and (v_old->>'list_price_minor') is distinct from (r->>'list_price_minor') then
          v_warn := v_warn || format('%s: sheet price %s ≠ CTP/Zoho price %s — NOT changed (Zoho is the price master)',
                                     r->>'sku', r->>'list_price_minor', coalesce(v_old->>'list_price_minor', 'none'));
        end if;
      end if;
    end loop;

    -- fitment
    for r in select * from jsonb_array_elements(coalesce(p->'fitment', '[]')) loop
      select id into v_part from part where upper(btrim(sku)) = upper(btrim(r->>'sku')) and deleted_at is null;
      select id into v_veh from vehicle_model where make = coalesce(nullif(r->>'make', ''), v_make)
         and model = coalesce(nullif(r->>'model', ''), v_model) and coalesce(variant, '') = coalesce(r->>'variant', '') and deleted_at is null;
      if v_part is null or v_veh is null then
        v_errors := v_errors || format('fitment %s → %s %s %s: %s', r->>'sku', coalesce(nullif(r->>'make', ''), v_make), coalesce(nullif(r->>'model', ''), v_model),
                                       coalesce(r->>'variant', ''), case when v_part is null then 'unknown SKU' else 'vehicle not in vehicles sheet' end);
        continue;
      end if;
      select id, to_jsonb(f) into v_id, v_old from part_fitment f where part_id = v_part and vehicle_id = v_veh and coalesce(engine, '') = coalesce(r->>'engine', '');
      if v_id is null then
        insert into part_fitment (part_id, vehicle_id, engine, year_from, year_to, note)
        values (v_part, v_veh, coalesce(r->>'engine', ''), nullif(r->>'year_from', '')::int, nullif(r->>'year_to', '')::int, nullif(r->>'note', ''))
        returning id into v_id;
        insert into import_batch_row (batch_code, entity, row_id, row_key, action) values (v_batch, 'part_fitment', v_id, r->>'sku', 'created');
      else
        update part_fitment set year_from = nullif(r->>'year_from', '')::int, year_to = nullif(r->>'year_to', '')::int, note = nullif(r->>'note', ''), deleted_at = null
         where id = v_id and (year_from, year_to, note, deleted_at) is distinct from (nullif(r->>'year_from', '')::int, nullif(r->>'year_to', '')::int, nullif(r->>'note', ''), null::timestamptz);
        if found then insert into import_batch_row (batch_code, entity, row_id, row_key, action, before) values (v_batch, 'part_fitment', v_id, r->>'sku', 'updated', v_old); end if;
      end if;
    end loop;

    -- cross-references / alternates
    for r in select * from jsonb_array_elements(coalesce(p->'xrefs', '[]')) loop
      select id into v_part from part where upper(btrim(sku)) = upper(btrim(r->>'sku')) and deleted_at is null;
      if v_part is null then v_errors := v_errors || format('xref %s: unknown SKU', r->>'sku'); continue; end if;
      insert into part_xref (part_id, xref_number, xref_brand, xref_type, confidence)
      values (v_part, r->>'xref_number', nullif(r->>'xref_brand', ''), coalesce(nullif(r->>'xref_type', ''), 'aftermarket'), coalesce(nullif(r->>'confidence', '')::int, 100))
      on conflict (part_id, xref_number, xref_type) do nothing returning id into v_id;
      if v_id is not null then insert into import_batch_row (batch_code, entity, row_id, row_key, action) values (v_batch, 'part_xref', v_id, r->>'sku', 'created'); end if;
      v_id := null;
    end loop;

    -- suppliers per part
    for r in select * from jsonb_array_elements(coalesce(p->'part_suppliers', '[]')) loop
      select id into v_part from part where upper(btrim(sku)) = upper(btrim(r->>'sku')) and deleted_at is null;
      select id into v_sup from supplier where code = r->>'supplier_code';
      if v_part is null or v_sup is null then
        v_errors := v_errors || format('part supplier %s / %s: %s', r->>'sku', r->>'supplier_code', case when v_part is null then 'unknown SKU' else 'unknown supplier code' end);
        continue;
      end if;
      select id, to_jsonb(s) into v_id, v_old from part_supplier s where part_id = v_part and supplier_id = v_sup;
      if v_id is null then
        insert into part_supplier (part_id, supplier_id, supplier_sku, cost_minor, currency, lead_time_days, moq, is_preferred)
        values (v_part, v_sup, nullif(r->>'supplier_sku', ''), nullif(r->>'cost_minor', '')::bigint, coalesce(nullif(r->>'currency', ''), 'ZAR'),
                nullif(r->>'lead_time_days', '')::int, nullif(r->>'moq', '')::int, coalesce((r->>'is_preferred')::boolean, false))
        returning id into v_id;
        insert into import_batch_row (batch_code, entity, row_id, row_key, action) values (v_batch, 'part_supplier', v_id, r->>'sku', 'created');
      else
        update part_supplier set supplier_sku = nullif(r->>'supplier_sku', ''), cost_minor = nullif(r->>'cost_minor', '')::bigint,
               currency = coalesce(nullif(r->>'currency', ''), 'ZAR'), lead_time_days = nullif(r->>'lead_time_days', '')::int,
               moq = nullif(r->>'moq', '')::int, is_preferred = coalesce((r->>'is_preferred')::boolean, false), deleted_at = null, updated_at = now()
         where id = v_id and (supplier_sku, cost_minor, currency, lead_time_days, moq, is_preferred, deleted_at) is distinct from
               (nullif(r->>'supplier_sku', ''), nullif(r->>'cost_minor', '')::bigint, coalesce(nullif(r->>'currency', ''), 'ZAR'),
                nullif(r->>'lead_time_days', '')::int, nullif(r->>'moq', '')::int, coalesce((r->>'is_preferred')::boolean, false), null::timestamptz);
        if found then insert into import_batch_row (batch_code, entity, row_id, row_key, action, before) values (v_batch, 'part_supplier', v_id, r->>'sku', 'updated', v_old); end if;
      end if;
    end loop;

    -- diagrams (per make: make/model from the profile)
    for r in select * from jsonb_array_elements(coalesce(p->'diagrams', '[]')) loop
      select id, to_jsonb(d) into v_dg, v_old from diagram d where drawing_key = r->>'drawing_key';
      if v_dg is not null and ((v_old->>'make') is distinct from v_make or coalesce(v_old->>'model', '') is distinct from v_model) then
        v_errors := v_errors || format('drawing %s belongs to %s %s', r->>'drawing_key', v_old->>'make', v_old->>'model'); continue;
      end if;
      if v_dg is null then
        insert into diagram (drawing_key, title, section_code, make, model, image_path, img_w, img_h, source)
        values (r->>'drawing_key', r->>'title', r->>'section_code', v_make, nullif(v_model, ''), r->>'image_path',
                nullif(r->>'img_w', '')::int, nullif(r->>'img_h', '')::int, 'onboard ' || v_batch)
        returning id into v_dg;
        insert into import_batch_row (batch_code, entity, row_id, row_key, action) values (v_batch, 'diagram', v_dg, r->>'drawing_key', 'created');
      else
        update diagram set title = r->>'title', section_code = r->>'section_code', image_path = r->>'image_path',
               img_w = nullif(r->>'img_w', '')::int, img_h = nullif(r->>'img_h', '')::int, deleted_at = null
         where id = v_dg and (title, section_code, image_path, img_w, img_h, deleted_at) is distinct from
               (r->>'title', r->>'section_code', r->>'image_path', nullif(r->>'img_w', '')::int, nullif(r->>'img_h', '')::int, null::timestamptz);
        if found then insert into import_batch_row (batch_code, entity, row_id, row_key, action, before) values (v_batch, 'diagram', v_dg, r->>'drawing_key', 'updated', v_old); end if;
      end if;
    end loop;

    -- hotspots (diagram + item no. + part)
    for r in select * from jsonb_array_elements(coalesce(p->'hotspots', '[]')) loop
      select id into v_dg from diagram where drawing_key = r->>'drawing_key' and deleted_at is null;
      select id into v_part from part where upper(btrim(sku)) = upper(btrim(r->>'sku')) and deleted_at is null;
      if v_dg is null or v_part is null then
        v_errors := v_errors || format('hotspot %s #%s → %s: %s', r->>'drawing_key', r->>'item_no', r->>'sku', case when v_dg is null then 'unknown drawing' else 'unknown SKU' end);
        continue;
      end if;
      select id, to_jsonb(h) into v_id, v_old from hotspot h where diagram_id = v_dg and part_id = v_part and item_no = r->>'item_no' and deleted_at is null;
      if v_id is null then
        insert into hotspot (diagram_id, part_id, item_no, x, y, radius)
        values (v_dg, v_part, r->>'item_no', (r->>'x')::float8, (r->>'y')::float8,
                coalesce(nullif(r->>'radius', '')::float8, (select greatest(20, round(img_w * 0.029)) from diagram where id = v_dg), 58)) returning id into v_id;   -- 58 px on a 1983-wide SEC drawing
        insert into import_batch_row (batch_code, entity, row_id, row_key, action) values (v_batch, 'hotspot', v_id, r->>'drawing_key' || '#' || (r->>'item_no'), 'created');
      else
        update hotspot set x = (r->>'x')::float8, y = (r->>'y')::float8, radius = coalesce(nullif(r->>'radius', '')::float8, radius)
         where id = v_id and (x, y, radius) is distinct from ((r->>'x')::float8, (r->>'y')::float8, coalesce(nullif(r->>'radius', '')::float8, radius));
        if found then insert into import_batch_row (batch_code, entity, row_id, row_key, action, before) values (v_batch, 'hotspot', v_id, r->>'drawing_key' || '#' || (r->>'item_no'), 'updated', v_old); end if;
      end if;
    end loop;

    -- photos (the files are uploaded by the tool first; here only the rows)
    for r in select * from jsonb_array_elements(coalesce(p->'images', '[]')) loop
      select id into v_part from part where upper(btrim(sku)) = upper(btrim(r->>'sku')) and deleted_at is null;
      if v_part is null then v_errors := v_errors || format('image %s: unknown SKU', r->>'sku'); continue; end if;
      if not exists (select 1 from part_image where part_id = v_part and path = r->>'path' and deleted_at is null) then
        insert into part_image (part_id, path, kind, is_primary, sort_order, caption)
        values (v_part, r->>'path', 'photo', case when coalesce((r->>'is_primary')::boolean, false) then 1 else 0 end,
                coalesce(nullif(r->>'sort_order', '')::int, 0), nullif(r->>'caption', '')) returning id into v_id;
        insert into import_batch_row (batch_code, entity, row_id, row_key, action) values (v_batch, 'part_image', v_id, r->>'sku', 'created');
      end if;
    end loop;

    -- rebate schemes (price books): which SKUs a scheme covers
    for r in select * from jsonb_array_elements(coalesce(p->'scheme_skus', '[]')) loop
      select id into v_sch from rebate_scheme where name = r->>'scheme';
      if v_sch is null then v_errors := v_errors || format('scheme "%s" (for %s) does not exist', r->>'scheme', r->>'sku'); continue; end if;
      insert into rebate_scheme_sku (scheme_id, sku, source) values (v_sch, btrim(r->>'sku'), 'onboard ' || v_batch)
        on conflict (scheme_id, sku) do nothing;
      if found then insert into import_batch_row (batch_code, entity, row_id, row_key, action) values (v_batch, 'rebate_scheme_sku', v_sch, v_sch || ':' || btrim(r->>'sku'), 'created'); end if;
    end loop;

    select jsonb_object_agg(k, n) into c from (
      select entity || ':' || action k, count(*) n from import_batch_row where batch_code = v_batch and at >= now() group by 1) s;
    v_result := jsonb_build_object('batch', v_batch, 'dry_run', p_dry_run, 'ok', cardinality(v_errors) = 0,
                                   'errors', to_jsonb(v_errors), 'warnings', to_jsonb(v_warn), 'counts', coalesce(c, '{}'::jsonb));
    update import_batch set summary = v_result, updated_at = now() where code = v_batch;
    if p_dry_run or cardinality(v_errors) > 0 then
      raise exception using errcode = 'P0001', message = 'onboard: undo';
    end if;
  exception when sqlstate 'P0001' then
    if sqlerrm <> 'onboard: undo' then raise; end if;
    -- dry run or errors: everything above was undone; v_result still says what it would have done
  end;
  return v_result;
end $$;
revoke all on function public.onboard_import(jsonb, boolean) from public, anon, authenticated;
grant execute on function public.onboard_import(jsonb, boolean) to service_role;

-- ── rollback ─────────────────────────────────────────────────────────────────
-- Zoho first (tools/onboard deactivates the batch's Zoho items through zoho-onboard), then this.
-- Updated rows get their "before" back; created rows are soft-deleted (deleted_at), or with
-- p_purge (TEST batches only) hard-deleted. Rows created later by anything else are never touched.
create or replace function public.onboard_rollback(p_batch text, p_purge boolean default false, p_dry_run boolean default true)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare b record; x record; v_cols text; v_n jsonb := '{}'::jsonb; v_result jsonb; v_open int;
  -- children first
  ord constant text[] := array['hotspot', 'part_image', 'part_xref', 'part_fitment', 'part_supplier', 'rebate_scheme_sku', 'price',
                               'diagram', 'part', 'vehicle_model', 'category', 'supplier', 'brand', 'make_profile'];
begin
  if auth.uid() is not null then raise exception 'onboard_rollback is run by the server.' using errcode = '42501'; end if;
  select * into b from import_batch where code = p_batch;
  if b.code is null then raise exception 'no batch %', p_batch; end if;
  if b.status <> 'imported' then return jsonb_build_object('batch', p_batch, 'skipped', 'already ' || b.status); end if;
  if p_purge and not b.is_test then raise exception 'purge is only for TEST batches; % is not one — roll back without purge', p_batch; end if;
  select count(*) into v_open from import_batch_row r where r.batch_code = p_batch and r.action = 'zoho_created'
     and not exists (select 1 from import_batch_row d where d.batch_code = p_batch and d.action = 'zoho_deactivated' and d.zoho_id = r.zoho_id);
  if v_open > 0 then
    raise exception '% Zoho item(s) this batch created are still active — run "onboard.py rollback" (it deactivates them first)', v_open;
  end if;

  begin
    for x in select r.*, array_position(ord, r.entity) o from import_batch_row r
              where r.batch_code = p_batch and r.action in ('created', 'updated') and r.entity <> 'zoho_item'
              order by array_position(ord, r.entity), r.id desc loop
      if x.action = 'updated' then
        select string_agg(format('%I = (jsonb_populate_record(null::%I, $1)).%I', k, x.entity, k), ', ') into v_cols
          from jsonb_object_keys(x.before) k
         where k not in ('id', 'rev', 'updated_at')
           and exists (select 1 from information_schema.columns ic where ic.table_schema = 'public' and ic.table_name = x.entity and ic.column_name = k);
        execute format('update %I set %s where id = $2', x.entity, v_cols) using x.before, x.row_id;
      elsif x.entity = 'rebate_scheme_sku' then
        delete from rebate_scheme_sku where scheme_id = x.row_id and sku = split_part(x.row_key, ':', 2) and source = 'onboard ' || p_batch;
      elsif x.entity = 'make_profile' then
        if p_purge then delete from make_profile where id = x.row_id; else update make_profile set active = false, updated_at = now() where id = x.row_id; end if;
      elsif p_purge or x.entity = 'price' then
        if x.entity = 'part' then
          update zoho_item set part_id = null where part_id = x.row_id;
          delete from price where part_id = x.row_id; delete from part_cost where part_id = x.row_id;
        end if;
        execute format('delete from %I where id = $1', x.entity) using x.row_id;
      else
        execute format('update %I set deleted_at = now() where id = $1 and deleted_at is null', x.entity) using x.row_id;
      end if;
      v_n := jsonb_set(v_n, array[x.entity || ':' || x.action], to_jsonb(coalesce((v_n->>(x.entity || ':' || x.action))::int, 0) + 1));
    end loop;
    v_result := jsonb_build_object('batch', p_batch, 'dry_run', p_dry_run, 'purge', p_purge, 'undone', v_n);
    if p_dry_run then raise exception using errcode = 'P0001', message = 'onboard: undo'; end if;
    insert into import_batch_row (batch_code, entity, action) values (p_batch, 'import_batch', 'rolled_back');
    update import_batch set status = case when p_purge then 'purged' else 'rolled_back' end, updated_at = now(),
           summary = coalesce(summary, '{}'::jsonb) || jsonb_build_object('rollback', v_result) where code = p_batch;
  exception when sqlstate 'P0001' then
    if sqlerrm <> 'onboard: undo' then raise; end if;
  end;
  return v_result;
end $$;
revoke all on function public.onboard_rollback(text, boolean, boolean) from public, anon, authenticated;
grant execute on function public.onboard_rollback(text, boolean, boolean) to service_role;

commit;
